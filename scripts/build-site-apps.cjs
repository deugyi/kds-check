/* Generated entry HTML shares all CSS/JS/data with the main application. */
'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
function render(source,site){
 if(!['south','north'].includes(site))throw Error('Unknown site app');
 const name=site==='south'?'남측':'북측';
 let html=source.replace(/\r\n/g,'\n').replace('<html lang="ko">',`<html lang="ko" data-site-app="${site}">`)
  .replace('<head>','<head>\n<!-- Generated by npm run build:sites; edit app-template.html. -->\n<base href="./">')
  .replace(/<title>[^<]*<\/title>/,`<title>사이트원 · 서리풀 : ${name}</title>`);
 // Process intake/approval is retained in the source template for future work,
 // but is not mounted or loaded in either current site app.
 const omit=new Set(['site-morning-ui.js','site-progress-ui.js','supabase/functions/_shared/progress-core.js','supabase/functions/_shared/morning-core.js',...(site==='north'?['prd-ui.js','site-plan-ui.js','site-reports-ui.js']:[])]);
 html=html.replace(/<script src="([^"?]+)(?:\?[^"\n]*)?"><\/script>\n?/g,(tag,file)=>omit.has(file)?'':tag);
 html=html.replace(/<section\b[^>]*\bid="site-progress"[^>]*>[\s\S]*?<\/section>\s*/,'')
  .replace(/<div class="menu"><button[^>]*data-t="site-progress"[^>]*>[\s\S]*?<\/button><\/div>\s*/,'')
  .replace(/<link[^>]*href="site-progress\.css[^"\n]*"[^>]*>\n?/g,'');
 if(!html.includes(`data-site-app="${site}"`)||!html.includes('<base href="./">')||!html.includes('site-app.js?'))throw Error('Shared HTML markers changed');
 return html;
}
if(require.main===module){
 const target=path.join(root,'app-target.json'),check=process.argv.includes('--check');
 if(fs.existsSync(target)){
  const {site}=JSON.parse(fs.readFileSync(target,'utf8')),source=fs.readFileSync(path.join(root,'app-template.html'),'utf8');
  const file=path.join(root,'index.html'),html=render(source,site);
  if(check){if(!fs.existsSync(file)||fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n')!==html)throw Error(`Run npm run build:sites: ${site}/index.html is stale`);}
  else{fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,html);}
  console.log(check?'Dedicated site entrance is current.':`Generated ${site} app entrance.`);
 }else{
  console.log('Main application: no dedicated app target configured.');
 }
}
module.exports={render};
